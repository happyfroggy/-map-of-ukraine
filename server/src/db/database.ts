import { mkdirSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';
import pg from 'pg';

// PostgreSQL schema. All timestamps are epoch milliseconds (BIGINT) to keep time math trivial.
const SCHEMA = `
CREATE TABLE IF NOT EXISTS regions (
  id          TEXT PRIMARY KEY,
  name        TEXT NOT NULL,
  sort_order  INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS questions (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  region_id         TEXT NOT NULL REFERENCES regions(id) ON DELETE CASCADE,
  type              TEXT NOT NULL CHECK (type IN ('choice', 'text')),
  prompt            TEXT NOT NULL,
  options           TEXT,     -- JSON array of 4 strings (choice only)
  correct_index     INTEGER,  -- 0..3 (choice only)
  accepted_answers  TEXT,     -- JSON array of accepted strings (text only)
  created_at        BIGINT NOT NULL,
  updated_at        BIGINT NOT NULL,
  CHECK (
    (type = 'choice' AND options IS NOT NULL AND correct_index BETWEEN 0 AND 3)
    OR (type = 'text' AND accepted_answers IS NOT NULL)
  )
);
CREATE INDEX IF NOT EXISTS idx_questions_region ON questions(region_id);

CREATE TABLE IF NOT EXISTS game_sessions (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_code   TEXT NOT NULL UNIQUE,
  status      TEXT NOT NULL DEFAULT 'lobby' CHECK (status IN ('lobby', 'active', 'finished')),
  created_at  BIGINT NOT NULL,
  started_at  BIGINT,
  ended_at    BIGINT
);

CREATE TABLE IF NOT EXISTS players (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id   INTEGER NOT NULL REFERENCES game_sessions(id) ON DELETE CASCADE,
  first_name   TEXT NOT NULL,
  last_name    TEXT NOT NULL,
  token        TEXT NOT NULL UNIQUE,  -- lets a player reconnect after a page reload
  joined_at    BIGINT NOT NULL,
  finished_at  BIGINT                 -- set when all regions are resolved
);
CREATE INDEX IF NOT EXISTS idx_players_session ON players(session_id);

CREATE TABLE IF NOT EXISTS region_attempts (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player_id      INTEGER NOT NULL REFERENCES players(id) ON DELETE CASCADE,
  region_id      TEXT NOT NULL REFERENCES regions(id),
  question_ids   TEXT NOT NULL,       -- JSON array: the 3 questions drawn for this player
  correct_count  INTEGER NOT NULL DEFAULT 0,
  wrong_count    INTEGER NOT NULL DEFAULT 0,
  status         TEXT NOT NULL DEFAULT 'in_progress' CHECK (status IN ('in_progress', 'green', 'red')),
  opened_at      BIGINT NOT NULL,
  resolved_at    BIGINT,
  UNIQUE (player_id, region_id)
);

CREATE TABLE IF NOT EXISTS answers (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  attempt_id    INTEGER NOT NULL REFERENCES region_attempts(id) ON DELETE CASCADE,
  question_id   INTEGER REFERENCES questions(id) ON DELETE SET NULL,
  given_answer  TEXT NOT NULL,
  is_correct    BOOLEAN NOT NULL,
  answered_at   BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_answers_attempt ON answers(attempt_id);

CREATE TABLE IF NOT EXISTS app_meta (
  key    TEXT PRIMARY KEY,
  value  TEXT NOT NULL
);

-- Migrations (idempotent, safe to run on every start) --------------------
-- v2 (retry rounds, superseded by drones; kept so existing databases stay valid)
ALTER TABLE region_attempts ADD COLUMN IF NOT EXISTS round INTEGER NOT NULL DEFAULT 1;
-- v3 drones: correct_count = drones shot down, wrong_count = mistakes;
-- the question currently shown for the next drone (so re-opening resumes it).
ALTER TABLE region_attempts ADD COLUMN IF NOT EXISTS current_question_id INTEGER REFERENCES questions(id) ON DELETE SET NULL;
`;

export type SqlParam = string | number | boolean | null;

/** Something you can run queries on: the pool, or a transaction. Placeholders are $1, $2, … */
export interface Queryable {
  get<T>(sql: string, ...params: SqlParam[]): Promise<T | undefined>;
  all<T>(sql: string, ...params: SqlParam[]): Promise<T[]>;
  /** Returns the number of affected rows. */
  run(sql: string, ...params: SqlParam[]): Promise<number>;
}

export interface Database extends Queryable {
  /** Runs fn in a transaction; use the given `q` (not the database) for every query inside it. */
  tx<T>(fn: (q: Queryable) => Promise<T>): Promise<T>;
  close(): Promise<void>;
}

type RawQuery = (sql: string, params: SqlParam[]) => Promise<{ rows: unknown[]; count: number }>;

function queryable(raw: RawQuery): Queryable {
  return {
    async get<T>(sql: string, ...params: SqlParam[]) {
      return (await raw(sql, params)).rows[0] as T | undefined;
    },
    async all<T>(sql: string, ...params: SqlParam[]) {
      return (await raw(sql, params)).rows as T[];
    },
    async run(sql: string, ...params: SqlParam[]) {
      return (await raw(sql, params)).count;
    },
  };
}

// BIGINT (timestamps, COUNT) and NUMERIC (SUM) arrive as strings by default — our values fit in a JS number.
const INT8 = 20;
const NUMERIC = 1700;

export interface DatabaseOptions {
  /** postgres:// connection string (production, e.g. Neon). */
  url?: string;
  /** Otherwise an embedded PGlite database in this directory, or ':memory:'. */
  dir?: string;
}

export async function openDatabase({ url, dir = ':memory:' }: DatabaseOptions): Promise<Database> {
  const db = url ? openPostgres(url) : await openPglite(dir);
  await db.run(SCHEMA);
  return db;
}

function openPostgres(url: string): Database {
  pg.types.setTypeParser(INT8, Number);
  pg.types.setTypeParser(NUMERIC, Number);
  const pool = new pg.Pool({ connectionString: withStrictSsl(url), max: 5, idleTimeoutMillis: 30_000 });
  pool.on('error', (err) => console.error('[db] idle client error', err.message));

  const raw =
    (client: pg.Pool | pg.PoolClient): RawQuery =>
    async (sql, params) => {
      const r = await client.query(sql, params.length ? params : undefined);
      return { rows: r.rows, count: r.rowCount ?? 0 };
    };

  return {
    ...queryable(raw(pool)),
    async tx(fn) {
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        const result = await fn(queryable(raw(client)));
        await client.query('COMMIT');
        return result;
      } catch (err) {
        await client.query('ROLLBACK').catch(() => {});
        throw err;
      } finally {
        client.release();
      }
    },
    close: () => pool.end(),
  };
}

/**
 * pg 8 already treats sslmode=require as verify-full (certificate + hostname checked);
 * pg 9 will weaken it to libpq semantics. Pin the strict mode explicitly.
 */
function withStrictSsl(url: string): string {
  try {
    const u = new URL(url);
    const mode = u.searchParams.get('sslmode');
    if (mode === 'prefer' || mode === 'require' || mode === 'verify-ca') u.searchParams.set('sslmode', 'verify-full');
    return u.toString();
  } catch {
    return url;
  }
}

async function openPglite(dir: string): Promise<Database> {
  if (dir !== ':memory:') mkdirSync(dir, { recursive: true });
  const pglite = await PGlite.create(dir === ':memory:' ? undefined : dir, {
    parsers: { [INT8]: Number, [NUMERIC]: Number },
  });

  const raw =
    (client: Pick<PGlite, 'query' | 'exec'>): RawQuery =>
    async (sql, params) => {
      if (!params.length && sql.includes(';')) {
        await client.exec(sql); // multi-statement (schema)
        return { rows: [], count: 0 };
      }
      const r = await client.query(sql, params);
      return { rows: r.rows, count: r.affectedRows ?? 0 };
    };

  return {
    ...queryable(raw(pglite)),
    tx: (fn) => pglite.transaction((tx) => fn(queryable(raw(tx)))),
    close: () => pglite.close(),
  };
}
